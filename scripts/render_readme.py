"""Write the generated parts of the README from results/metrics.json.

    python scripts/render_readme.py           rewrite the generated blocks
    python scripts/render_readme.py --check   exit 1 if the README is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- {name}:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- {name}:end -->"


def pct(x: float, d: int = 2) -> str:
    return f"{100 * x:+.{d}f}%"


def sig(p: float) -> bool:
    return p < 0.05


def late_sentence(late: dict) -> str:
    base = "Late filings, the signal this repository was first built on"
    if not sig(late["p"]):
        return f"{base}, are not more informative ({pct(late['diff'])} signed over 20 days, t = {late['t']:.1f})."
    if late["diff"] > 0:
        return f"{base}, are more informative ({pct(late['diff'])} signed over 20 days, t = {late['t']:.1f})."
    rb = late["robust"]
    return (
        f"{base}, point the wrong way: after a trade filed past the 45 day limit the stock moves against "
        f"the member's position, {pct(late['diff'])} signed over 20 days relative to on-time filings "
        f"(t = {late['t']:.1f}), and this holds with extreme returns trimmed and errors clustered by member "
        f"(t = {rb['winsorized_member_cluster_t']:.1f}) and without the five members who file late most "
        f"(t = {rb['without_top5_t']:.1f})."
    )


def headline(m: dict) -> str:
    s, c, cal, late, holm = m["sample"], m["car"], m["calendar"], m["late"], m["holm"]
    survivors = [k for k, v in holm.items() if v < 0.05]
    effect = {
        "buy minus sell, 5 days": c["5"]["diff"],
        "buy minus sell, 20 days": c["20"]["diff"],
        "buy minus sell, 60 days": c["60"]["diff"],
        "long-short portfolio, CAPM alpha": cal["long_short_capm_alpha_annual"],
        "long-short portfolio, three-factor alpha": cal["long_short_ff3_alpha_annual"],
        "late minus on-time filings": late["diff"],
    }
    follow = [k for k in survivors if effect[k] > 0]  # surviving evidence for copying members
    pre = c["pre"]
    tradable = (
        "None of the six tradable tests survives a multiple-testing correction."
        if not survivors
        else f"Of the six tradable tests, {len(survivors)} {'survives' if len(survivors) == 1 else 'survive'} a multiple-testing correction "
        f"({'; '.join(survivors)}), and {'it does not' if len(survivors) == 1 and not follow else 'none of them does' if not follow else f'{len(follow)} of them do'} favour copying members."
    )
    pre_txt = (
        f"Before the filing, stocks members bought beat the stocks they sold by {pct(pre['diff'])} "
        f"against the market (t = {pre['t']:.1f})"
        if sig(pre["p"])
        else f"Before the filing, stocks members bought and sold did not differ clearly "
        f"({pct(pre['diff'])}, t = {pre['t']:.1f})"
    )
    return (
        f"**Answer, from {s['events_with_prices']:,} House stock trades disclosed between "
        f"{s['first_filing'][:4]} and {s['last_filing'][:7]} by {s['members']} members: "
        f"{'no' if not follow else 'partly'}.** {pre_txt}, a window no outsider can trade. "
        f"From the day after the report is filed, purchases minus sales earn {pct(c['20']['diff'])} "
        f"over 20 trading days (t = {c['20']['t']:.1f}) and {pct(c['60']['diff'])} over 60 "
        f"(t = {c['60']['t']:.1f}). A portfolio long what members bought and short what they sold, "
        f"each held 20 days after the filing, has a three-factor alpha of "
        f"{pct(cal['long_short_ff3_alpha_annual'], 1)} a year (t = {cal['long_short_ff3_t']:.1f}). "
        f"{late_sentence(late)} {tradable}"
    )


def results(m: dict) -> str:
    s, c, cal, late = m["sample"], m["car"], m["calendar"], m["late"]
    lines = [
        f"{s['rows_parsed']:,} transactions parsed from electronic House periodic transaction "
        f"reports; {s['stock_events']:,} are stock purchases or sales filed from {s['first_filing'][:4]} with a usable "
        f"lag; {s['events_with_prices']:,} have Yahoo prices ({s['tickers']:,} tickers; "
        f"{s['purchases']:,} purchases, {s['sales']:,} sales). Median gap from trade to filing: "
        f"{s['lag_median']:.0f} days; {100 * s['late_share']:.0f}% are filed after the 45 day limit.",
        "",
        "| Window | Events | Purchases | Sales | Purchases minus sales | t |",
        "|---|---|---|---|---|---|",
    ]
    names = {"pre": "Trade to filing (not tradable)", "5": "5 days after filing", "20": "20 days after filing", "60": "60 days after filing"}
    for k, label in names.items():
        r = c[k]
        lines.append(
            f"| {label} | {r['n']:,} | {pct(r['buy_mean'])} | {pct(r['sell_mean'])} | {pct(r['diff'])} | {r['t']:.1f} |"
        )
    lines += [
        "",
        "Abnormal returns are against the market, summed in logs. t statistics cluster by filing date.",
        "",
        "| Calendar-time portfolio, 20 day hold | Alpha a year | t |",
        "|---|---|---|",
        f"| Long purchases, short sales, CAPM | {pct(cal['long_short_capm_alpha_annual'], 1)} | {cal['long_short_capm_t']:.1f} |",
        f"| Long purchases, short sales, three factors | {pct(cal['long_short_ff3_alpha_annual'], 1)} | {cal['long_short_ff3_t']:.1f} |",
        f"| Long purchases only, CAPM | {pct(cal['long_only_excess_capm_alpha_annual'], 1)} | {cal['long_only_excess_capm_t']:.1f} |",
        f"| Long purchases only, three factors | {pct(cal['long_only_excess_ff3_alpha_annual'], 1)} | {cal['long_only_excess_ff3_t']:.1f} |",
        "",
        f"{cal['days']:,} trading days from {cal['first_day']} to {cal['last_day']}; Newey-West 5 lags. "
        f"Long-short Sharpe ratio {cal['long_short_sharpe']:.2f} before costs.",
        "",
        f"Late filings ({late['n_late']:,} events): signed 20 day abnormal return {pct(late['signed_late'])} "
        f"against {pct(late['signed_on_time'])} for on-time filings (difference t = {late['t']:.1f}). With "
        f"returns winsorized at 1 and 99 percent and errors clustered by member: "
        f"{pct(late['robust']['winsorized_member_cluster_diff'])} (t = {late['robust']['winsorized_member_cluster_t']:.1f}). "
        f"Without the five members with the most late filings ({100 * late['robust']['top5_late_filers_share']:.0f}% "
        f"of them): {pct(late['robust']['without_top5_diff'])} (t = {late['robust']['without_top5_t']:.1f}). "
        f"Winsorized purchases minus sales: "
        + ", ".join(f"{h} days {pct(v['diff'])} (t = {v['t']:.1f})" for h, v in m["car_winsorized"].items())
        + ".",
        "",
        "| Test | p | Holm p |",
        "|---|---|---|",
    ]
    for k, p in m["raw_p"].items():
        lines.append(f"| {k} | {p:.3f} | {m['holm'][k]:.3f} |")
    return "\n".join(lines)


def fill(text: str, name: str, body: str) -> str:
    a = text.index(MARK.format(name=name)) + len(MARK.format(name=name))
    b = text.index(END.format(name=name))
    return text[:a] + "\n" + body + "\n" + text[b:]


def main() -> None:
    m = json.loads((ROOT / "results" / "metrics.json").read_text())
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = fill(fill(text, "headline", headline(m)), "results", results(m))
    if "--check" in sys.argv:
        if new != text:
            print("README is out of date; run python scripts/render_readme.py")
            sys.exit(1)
        print("README matches results/metrics.json")
        return
    readme.write_text(new)
    print("README rendered")


if __name__ == "__main__":
    main()
